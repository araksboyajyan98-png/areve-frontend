import test from "node:test";
import assert from "node:assert/strict";

import { isValidPhone } from "../src/features/ContactForm/lib/phone.ts";

/*
 * Разбор телефона написан дважды: здесь — чтобы родитель увидел ошибку сразу,
 * и на сервере — чтобы привести номер к одному виду. Репозитории разные,
 * общего кода нет, поэтому договор записан таблицей ниже.
 *
 * ЭТОТ ЖЕ НАБОР ЛЕЖИТ В areve-backend. Меняете правило — меняйте в обоих,
 * иначе форма пропустит номер, а сервер ответит «проверьте поля», и родитель
 * не поймёт, что не так.
 */

export const VALID = [
  // как их дал центр
  "095 313 633",
  "094 505 552",
  // те же номера в других записях
  "+374 95 313 633",
  "+37495313633",
  "37495313633",
  "0-95-31-36-33",
  "(095) 313-633",
  // без кода страны и без ведущего нуля
  "95313633",
];

export const INVALID = [
  "",
  "   ",
  "123",
  "095 313 63", // на цифру короче
  "0953136330", // на цифру длиннее
  "+7 999 123 45 67", // российский номер
  "abc",
];

test("настоящие номера центра проходят", () => {
  for (const input of VALID) {
    assert.equal(isValidPhone(input), true, `форма отвергла: ${JSON.stringify(input)}`);
  }
});

test("непохожее на армянский номер отвергается", () => {
  for (const input of INVALID) {
    assert.equal(isValidPhone(input), false, `форма приняла: ${JSON.stringify(input)}`);
  }
});

test("номер на цифру короче не принимается за номер без кода страны", () => {
  /*
   * Ошибка, которую этот случай однажды поймал: «095 313 63» — восемь цифр
   * с ведущим нулём — считалось номером без кода страны, и ноль уезжал
   * в код оператора. Заявка ушла бы с несуществующим телефоном.
   */
  assert.equal(isValidPhone("095 313 63"), false);
  assert.equal(isValidPhone("37409531363"), false);
});
